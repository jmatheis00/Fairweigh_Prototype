import { DEMO_DATA_NOTICE, RISK_MONITORING, SOURCE_FILES, SOURCE_SYSTEMS, type DemoDataset, type SourceSystem } from '@scc/shared';

/**
 * README files for data/sources/: what each folder simulates, what is in it and
 * which agent tool reads it. Generated, so counts always match the data.
 */
export function sourceReadmes(d: DemoDataset): Record<string, string> {
  const docs = (heldBy: SourceSystem, type?: string) =>
    d.documents.filter((x) => x.heldBy === heldBy && (!type || x.documentType === type)).length;
  const header = (system: SourceSystem) =>
    `# ${SOURCE_SYSTEMS[system].label}\n\n**Simulates:** ${SOURCE_SYSTEMS[system].simulates}.\n\n` +
    `${DEMO_DATA_NOTICE}: every company, value and document here is invented (team Excel \`${d.generatedFrom}\`, ` +
    'plus `data/assumptions.json`). Generated by `npm run data:build`; do not edit by hand.\n\n';
  const file = (path: string) => `\`${path.split('/').slice(1).join('/')}\``;

  return {
    'README.md':
      '# Simulated source systems\n\n' +
      'The agent collects every value from these systems, one folder each. In a real installation they would be ' +
      "separate systems with their own owners and interfaces: the client's ERP, partners with sustainability data, " +
      'and documents from suppliers. Here they are folders, generated from the team Excel.\n\n' +
      '| Folder | System | Agent tool |\n|---|---|---|\n' +
      `| \`${SOURCE_SYSTEMS.erp.folder}/\` | ${SOURCE_SYSTEMS.erp.label} | \`get_erp_record\` |\n` +
      `| \`${SOURCE_SYSTEMS.ratings.folder}/\` | ${SOURCE_SYSTEMS.ratings.label} | \`get_rating\` |\n` +
      `| \`${SOURCE_SYSTEMS.pcf.folder}/\` | ${SOURCE_SYSTEMS.pcf.label} | \`get_pcf\` |\n` +
      `| \`${SOURCE_SYSTEMS.documents.folder}/\` | ${SOURCE_SYSTEMS.documents.label} | \`list_documents\`, \`read_document\` |\n` +
      `| \`${RISK_MONITORING.folder}/\` | ${RISK_MONITORING.label} | none (shown in the dashboards) |\n` +
      '| `public-benchmarks/` | Real published industry averages for the CO₂ benchmark (not fictitious) | none |\n' +
      '| `cockpit/` | Configuration of the cockpit itself (catalog, benchmarks, thresholds, example decisions) | none |\n\n' +
      `${DEMO_DATA_NOTICE}.\n`,

    [`${SOURCE_SYSTEMS.erp.folder}/README.md`]:
      header('erp') +
      '| File | Content |\n|---|---|\n' +
      `| ${file(SOURCE_FILES.erpSuppliers)} | Supplier master and performance: ${d.erp.length} suppliers with status, spend, contract, lead time, on-time delivery, complaint rate, VAT and ERP ID |\n` +
      `| ${file(SOURCE_FILES.erpQuotations)} | ${d.offers.length} quotations registered for the current requests (the PDFs are in \`supplier-documents/\`) |\n` +
      `| ${file(SOURCE_FILES.erpPurchaseOrders)} | ${d.purchaseOrders.length} purchase orders of the three products, January 2025 to September 2026 |\n` +
      `| ${file(SOURCE_FILES.erpRequisitions)} | ${d.purchaseRequisitions.length} purchase requisitions for the buyer's work queue (${d.purchaseRequisitions.filter((r) => r.status === 'open').length} open, the others started or closed as sample work) |\n` +
      `| ${file(SOURCE_FILES.erpPerformance)} | Vendor evaluation per supplier and month (${d.supplierPerformance.length} rows): deliveries, on-time deliveries, quality notifications, spend. The KPIs in suppliers.json are the sums of the last 12 months |\n` +
      `| \`purchase-orders/\` | ${docs('erp', 'purchase_order')} order PDFs, one per purchase order |\n` +
      `| ${file(SOURCE_FILES.erpDocuments)} | Index of the order PDFs with their text |\n`,

    [`${SOURCE_SYSTEMS.ratings.folder}/README.md`]:
      header('ratings') +
      '| File | Content |\n|---|---|\n' +
      `| ${file(SOURCE_FILES.ratings)} | ${d.ratings.length} ratings: score 0–100, LkSG country risk, certificates, SBTi target, report, controversies, CO₂ data source |\n` +
      `| \`scorecards/\` | ${docs('ratings', 'rating_scorecard')} scorecard PDFs, one per rated supplier |\n` +
      `| ${file(SOURCE_FILES.ratingHistory)} | ${d.ratingHistory.length} assessments: score per year, the current one first in the ratings |\n` +
      `| ${file(SOURCE_FILES.certificates)} | ${d.certificates.length} certificates with validity (PDFs of the suppliers in current requests are in \`supplier-documents/certificates/\`) |\n` +
      `| ${file(SOURCE_FILES.companyEmissions)} | Company-level emissions (CSRD style): Scope 1+2, CO₂ intensity per EUR, renewable energy share, transport distance, data completeness |\n` +
      `| ${file(SOURCE_FILES.ratingDocuments)} | Index of the scorecards with their text |\n`,

    [`${SOURCE_SYSTEMS.pcf.folder}/README.md`]:
      header('pcf') +
      '| File | Content |\n|---|---|\n' +
      `| ${file(SOURCE_FILES.pcf)} | ${d.pcf.length} product footprints (kg CO₂e per piece) with data-quality level, boundary, reference date and how each one arrived |\n\n` +
      'Data-quality levels (team data model): 1 Verified · 2 Supplier-specific · 3 Company estimate · 4 Industry average. ' +
      'Footprints that came as a document link to their data sheet in `supplier-documents/pcf-datasheets/`.\n',

    [`${SOURCE_SYSTEMS.documents.folder}/README.md`]:
      header('documents') +
      '| Folder or file | Content |\n|---|---|\n' +
      `| \`quotations/\` | ${docs('documents', 'offer')} quotation PDFs |\n` +
      `| \`pcf-datasheets/\` | ${docs('documents', 'pcf_datasheet')} PCF data sheets sent by suppliers |\n` +
      `| \`certificates/\` | ${docs('documents', 'certificate')} certificates (ISO 14001, SA8000, …) of the suppliers in current requests and orders |\n` +
      `| \`authority-notices/\` | ${docs('documents', 'fine_notice')} fine notice (proof of a legal violation, knock-out) |\n` +
      `| ${file(SOURCE_FILES.supplierDocuments)} | Index of these PDFs with their text, so the evidence check can find a value on its page |\n`,

    [`${RISK_MONITORING.folder}/README.md`]:
      `# ${RISK_MONITORING.label}\n\n**Simulates:** ${RISK_MONITORING.simulates}.\n\n` +
      `${DEMO_DATA_NOTICE}. Generated by \`npm run data:build\`; do not edit by hand.\n\n` +
      '| File | Content |\n|---|---|\n' +
      `| \`alerts.json\` | ${d.riskAlerts.length} alerts with date, severity and category |\n\n` +
      'Every alert restates a fact from the other systems (fine notice, controversy in the rating, LkSG country risk, ' +
      'certificate validity, rating history). Nothing new is invented about any supplier.\n',

    'public-benchmarks/README.md':
      '# Public benchmarks\n\n**Real, published data, not fictitious.** Industry averages per kg of material from official sources. ' +
      'They describe materials, not companies. The cockpit multiplies them by the material per piece to get an industry CO₂ average per piece ' +
      '(material only, no processing), shown as context next to the result; it does not count towards the score (17 Nov 2026). Input: `data/source/public-benchmarks.json`, checked on the date given per factor.\n\n' +
      '| Factor | Value | Year | Source |\n|---|---|---|---|\n' +
      d.publicBenchmarks
        .map((f) => `| ${f.material} | ${f.valueKgCo2ePerKg} kg ${f.gas} per kg | ${f.referenceYear} | [${f.publisher}](${f.url}) |`)
        .join('\n') +
      '\n\nThe score measures every criterion against today, i.e. the current supplier (price we pay today, its ERP figures ' +
      'and product footprint; category average as fallback). See `cockpit/settings.json`, fields `benchmarks` (reference values) ' +
      'and `industryCo2` (context) per part.\n',

    'cockpit/README.md':
      '# Cockpit configuration\n\nNot an external system: the catalog of parts, thresholds, the CO₂ price for the euro display, ' +
      `and ${d.exampleDecisions.length} example decisions for the decision log. ${DEMO_DATA_NOTICE}.\n`,
  };
}
